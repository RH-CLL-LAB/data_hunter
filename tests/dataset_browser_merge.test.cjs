const assert=require('node:assert/strict');
const merge=require('../Scripts/dataset_browser/merge_ui.js');
assert.equal(merge.KIND,'datahunter_study_facts_merge_request');
const plan={counts:{datasets:{add:2,present:0,conflict:1}},summary:['Dry run: would merge facts of study a into b','- catalogue entries: 2 added'],conflicts:[]};
const request=merge.buildRequest('a','b',true,plan);
assert.equal(request.kind,merge.KIND);assert.equal(request.schema_version,1);
assert.deepEqual([request.source,request.target,request.reviewed],['a','b',true]);
assert.deepEqual(request.plan_counts,plan.counts,'the previewed counts travel with the request');
assert(request.instructions.includes('No file holdings and no AI-use permission cross over'));
assert(!('plan_counts' in merge.buildRequest('a','b',true,null)),'a request saved without a preview carries no counts');
assert.throws(()=>merge.buildRequest('a','a',true),/same study/);
assert.throws(()=>merge.buildRequest('a','b',false),/reviewed the plan/);
assert.throws(()=>merge.buildRequest('','b',true),/Choose the study/);
assert.equal(merge.fileName('a','b'),'datahunter-merge-a-into-b.json');
assert.equal(merge.command('x.json'),'.venv/bin/python Scripts/merge_study_facts.py --request x.json --apply');
assert.equal(merge.planText(plan),plan.summary.join('\n'));
assert.equal(merge.planText({error:'invalid_study_id'}),'The plan could not be computed: invalid_study_id');
assert.equal(merge.planText(null),'');
console.log('Passed: merge request building, its guards, file name, command and plan text.');
