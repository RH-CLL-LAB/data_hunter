const assert=require('node:assert/strict');
const merge=require('../Scripts/dataset_browser/merge_ui.js');
assert.equal(merge.KIND,'datahunter_study_facts_merge_request');
const brief={id:'a-and-b-merged',name:'Merged A + B',question:'q',intended_use:'u',population:'',targets:'',inclusion:'',exclusion:''};
const preview={totals:{datasets:5,held_files:3},sources:[],overlaps:{}};
const request=merge.buildRequest(['a','b'],brief,true,preview);
assert.equal(request.kind,merge.KIND);assert.equal(request.schema_version,1);
assert.deepEqual(request.sources,['a','b'],'tick order is kept: the first study wins');
assert.equal(request.new_study.id,'a-and-b-merged');assert.equal(request.reviewed,true);
assert.deepEqual(request.preview_totals,preview.totals,'the previewed totals travel with the request');
assert(request.instructions.includes('No file holdings and no AI-use permission cross over'));
assert(!('preview_totals' in merge.buildRequest(['a'],brief,true,null)),'a request saved without a preview carries no totals');
assert.throws(()=>merge.buildRequest([],brief,true),/Tick at least one study/);
assert.throws(()=>merge.buildRequest(['a','a'],brief,true),/ticked twice/);
assert.throws(()=>merge.buildRequest(['a'],{...brief,id:'../x'},true),/ID of lowercase letters/);
assert.throws(()=>merge.buildRequest(['a'],{...brief,id:'Upper'},true),/ID of lowercase letters/,'the ID rule is the workspace rule: lowercase only');
assert.throws(()=>merge.buildRequest(['study-a'],{...brief,id:'study-a'},true),/one of the ticked studies/);
assert.throws(()=>merge.buildRequest(['a'],{...brief,question:' '},true),/question/);
assert.throws(()=>merge.buildRequest(['a'],brief,false),/reviewed the preview/);
const filled=merge.prefill([{id:'a',name:'Study A',brief:{question:'Qa',intended_use:'Ua'}},{id:'b',name:'Study B',brief:{question:'Qb',intended_use:''}}]);
assert.equal(filled.id,'a-and-b-merged');assert.equal(filled.name,'Merged: a + b');
assert.equal(filled.question,'[a] Qa\n\n[b] Qb','each study’s text is labelled with its study ID');
assert.equal(filled.intended_use,'[a] Ua','empty fields of a study are left out');
assert(merge.prefill(Array.from({length:12},(_,i)=>({id:'study-with-a-long-identifier-'+i}))).name.length<=160,'the suggested name fits the 160-character limit');
assert.equal(merge.fileName('x'),'datahunter-merged-study-x.json');
assert.equal(merge.command('x.json'),'.venv/bin/python Scripts/merge_study_facts.py --request x.json --apply');
const text=merge.planText({sources:[{study:'a',datasets:2,held_datasets:1,papers:3,licence_records:1,terms_screens:0,notices:4,held_files:1200,held_bytes:2500000}],overlaps:{datasets:['X'],papers:[],licences:[]},files:'Held files are not copied.'});
assert(text.includes('a: 2 catalogue entries (1 held), 3 papers')&&text.includes('2.5 MB'));
assert(text.includes('datasets in more than one study (1): the first ticked study wins')&&text.includes('Held files are not copied.'));
assert.equal(merge.planText({error:'invalid_study_id'}),'The preview could not be computed: invalid_study_id');
assert.equal(merge.planText(null),'');
assert.equal(merge.fetchProblem(200,'application/json; charset=utf-8'),'');
assert(merge.fetchProblem(404,'text/html;charset=utf-8').includes('restart it'),'a server without the endpoint is named as stale');
assert(merge.fetchProblem(500,'text/plain').includes('answered 500'));
assert.equal(merge.human(11565368192),'11.6 GB');assert.equal(merge.human(0),'0 B');
console.log('Passed: merged-study request, its guards, the suggested brief, file name, command and preview text.');
