#!/usr/bin/env python3
"""Create the empty workspace state a fresh Data Hunter checkout needs to build its site.

The site build reads a validation report, a catalogue selection report and their
receipts under data/interim/, plus the catalogue documents under docs/. In a
working project those are produced by validate_dataset_workspace.py and
document_dataset_selection.py from acquired sources. A fresh checkout has no
sources, so this script writes the equivalent empty state: zero datasets, zero
artifacts, no evidence, no permissions. It refuses to run when the registries
already list datasets, so it can never overwrite a real catalogue.
"""
import argparse
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path
import sys

CODE_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE_ROOT / 'src'))
from datahunter.workspace import workspace_root
ROOT = workspace_root(default=CODE_ROOT)

LICENCE_CHECKS_HEADING = 'License checks before registration or download'  # linked by generated pages; keep its wording


def digest(path):
    return sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')


def registries_are_empty(root):
    usage = json.loads((root / 'configs/dataset_study_usage.json').read_text())
    return not usage.get('datasets') and not usage.get('studies')


def ensure_empty_state(root=ROOT, force=False):
    """Write empty reports, receipts and catalogue documents. Returns the paths written."""
    root = Path(root)
    if not registries_are_empty(root):
        raise ValueError('registries_list_datasets_run_the_validation_and_catalogue_scripts_instead')
    receipt = root / 'data/interim/dataset_selection/latest.json'
    if receipt.exists() and not force:
        return []
    now = datetime.now(timezone.utc)
    stamp = now.strftime('%Y%m%dT%H%M%S%fZ')
    written = []

    # Catalogue documents rendered by the site.
    docs = root / 'docs'
    docs.mkdir(exist_ok=True)
    catalogue = docs / 'DATASET_SELECTION.md'
    catalogue.write_text(
        '# Dataset catalogue\n\n'
        'No datasets are registered in this workspace yet. Create a research study in Data Hunter, '
        'run its licence-first dataset search with the intake agent, and the catalogue, this document '
        'and the generated pages are rebuilt from the registered results.\n')
    priorities = docs / 'DATASET_ACTION_PRIORITIES.md'
    priorities.write_text(
        '# Dataset actions: priorities, requests and completion gates\n\n'
        'No datasets are registered yet, so there are no priorities, access routes or minimal requests to list.\n\n'
        f'## {LICENCE_CHECKS_HEADING}\n\n'
        'Before any registration or download, read the applicable data licence and access terms, retain the notice '
        'with its URL, retrieval date and hash, and record a decision with the licence-review agent. Holding a file '
        'is never permission to use it; lenient mode blocks only explicit applicable AI prohibitions, strict mode also '
        'requires explicit AI approval, and both require underlying access and use rights.\n')
    licences = docs / 'DATA_LICENSES_AND_AI_USE.md'
    licences.write_text(
        '# Data licences and allowed/restricted AI use\n\n'
        'This register is regenerated by `Scripts/audit_data_licenses.py` from `configs/data_licenses.json` once '
        'sources and their licence evidence are registered. The workspace holds no resources yet.\n\n'
        '## Modes\n\n'
        '- **Lenient** (default): underlying access and use rights are required; an explicit applicable AI '
        'prohibition blocks the AI criterion.\n'
        '- **Restrictive**: the same rights checks plus explicit AI approval.\n\n'
        'Local inference, remote inference, embeddings, training and redistribution are separate decisions. '
        'An AI-silent licence is not explicit approval. Never infer data rights from a software licence.\n')
    written += [catalogue, priorities, licences]

    # Validation report and receipt.
    validation_id = stamp
    validation = {
        'schema_version': 1, 'validation_id': validation_id, 'checked_at': now.isoformat(),
        'model_calls': 0, 'source_repairs': 0, 'data_moves': 0, 'payload_copies': 0,
        'scope': 'Empty workspace: no acquired sources, no prepared inputs.',
        'summary': {'dataset_entries': 0, 'locked_artifacts': 0, 'prepared_artifacts': 0,
                    'locked_integrity': {}, 'prepared_integrity': {}, 'structure': {},
                    'optimization': {}, 'benchmark': {}, 'categories': {}},
        'datasets': [], 'artifacts': [], 'prepared_artifacts': []}
    vreport = root / 'data/interim/dataset_validation' / validation_id / 'report.json'
    write_json(vreport, validation)
    write_json(root / 'data/interim/dataset_validation/latest.json', {
        'validation_id': validation_id, 'report': str(vreport.relative_to(root)), 'report_sha256': digest(vreport),
        'summary': validation['summary'], 'source_repairs': 0, 'data_moves': 0, 'payload_copies': 0, 'model_calls': 0})
    written += [vreport]

    # Selection report and receipt (bound to the catalogue document).
    selection = {
        'schema_version': 1, 'generated_at': now.isoformat(),
        'summary': {'entries': 0, 'priority': {}, 'workflow_relevance': {}, 'validation_id': validation_id,
                    'rechecked_unique_artifacts': 0, 'source_repairs': 0, 'downloads': 0, 'model_calls': 0,
                    'preaccess_coverage': {'current_registration_candidates': 0, 'documented_outcomes': 0,
                                           'public_dataset_or_route_agreement_reviewed': 0,
                                           'complete_current_package_terms_still_needed': 0,
                                           'deferred_registration_entries': 0, 'statuses': {}, 'rights_granted': 0}},
        'evidence': [], 'datasets': []}
    sreport = root / 'data/interim/dataset_selection' / stamp / 'selection.json'
    write_json(sreport, selection)
    write_json(receipt, {'selection': str(sreport.relative_to(root)), 'selection_sha256': digest(sreport),
                         'document': 'docs/DATASET_SELECTION.md', 'document_sha256': digest(catalogue),
                         'summary': selection['summary']})
    written += [sreport, receipt]
    return written


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--force', action='store_true', help='Rewrite the empty state even if receipts exist')
    args = parser.parse_args(argv)
    written = ensure_empty_state(args.root, args.force)
    print(json.dumps({'root': str(args.root), 'written': [str(p.relative_to(args.root)) for p in written]}))


if __name__ == '__main__':
    main()
